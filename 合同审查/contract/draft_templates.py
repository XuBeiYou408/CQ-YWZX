def match_template(contract_type: str) -> Dict[str, Any]:
    """根据输入的合同类型模糊匹配最权威的示范文本"""
    c_lower = (contract_type or "").lower().strip()
    
    for key, data in TEMPLATES.items():
        if key in c_lower or data["name"] in c_lower:
            return data
        for alias in data["aliases"]:
            if alias in c_lower or c_lower in alias:
                return data
                
    # 关键词包含回退
    if any(k in c_lower for k in ["买卖", "采购", "供货", "销售", "货物"]):
        return TEMPLATES["goods"]
    if any(k in c_lower for k in ["软件", "技术", "开发", "代码", "it", "外包"]):
        return TEMPLATES["software"]
    if any(k in c_lower for k in ["租赁", "房屋", "物业", "写字楼", "场地", "商铺"]):
        return TEMPLATES["lease"]
    if any(k in c_lower for k in ["劳动", "用工", "人事", "员工", "聘用", "雇佣"]):
        return TEMPLATES["labor"]
    if any(k in c_lower for k in ["保密", "nda", "商业秘密", "秘密"]):
        return TEMPLATES["nda"]
    if any(k in c_lower for k in ["借款", "借贷", "保证", "担保", "贷款"]):
        return TEMPLATES["loan"]
    if any(k in c_lower for k in ["咨询", "居间", "中介", "服务", "顾问"]):
        return TEMPLATES["consulting"]
        
    return TEMPLATES["goods"]


def build_breach_and_jurisdiction(
    client_role: str,
    special_terms: str = "",
    party_a: str = "甲方",
    party_b: str = "乙方"
) -> Tuple[str, str]:
    """依据代表立场 (甲方/乙方/中立) 智能生成对称且合规的违约与管辖条款"""
    role_str = (client_role or "").lower()
    spec_lower = (special_terms or "").lower()
    
    # 1. 管辖权判定
    if "甲方" in spec_lower or "原告" in spec_lower or "采购方" in spec_lower:
        jurisdiction = "向甲方所在地有管辖权的人民法院提起诉讼"
    elif "乙方" in spec_lower or "供应商" in spec_lower:
        jurisdiction = "向乙方所在地有管辖权的人民法院提起诉讼"
    elif "仲裁" in spec_lower:
        jurisdiction = "向双方约定的仲裁委员会申请仲裁"
    elif "甲方" in role_str:
        jurisdiction = "向甲方住所地有管辖权的人民法院提起诉讼"
    elif "乙方" in role_str:
        jurisdiction = "向乙方住所地有管辖权的人民法院提起诉讼"
    else:
        jurisdiction = "向原告住所地或合同履行地有管辖权的人民法院提起诉讼"

    # 2. 违约责任定制
    rate_hint = "日万分之五"
    cap_hint = "合同总价款的 10%"
    if "万分之" in spec_lower:
        m = re.search(r'(日?万分之[一二三四五六七八九十0-9]+)', special_terms)
        if m: rate_hint = m.group(1)
    if "不超过" in spec_lower or "%" in spec_lower:
        m = re.search(r'(不超过[^\s，。]+)', special_terms)
        if m: cap_hint = m.group(1)

    if "甲方" in role_str:
        breach = f"""违约金约定：任何一方违反本合同约定，应当按照《民法典》法定标准承担违约赔偿责任。违约金计算标准按逾期部分金额的 {rate_hint} 按日计收，累计违约金上限不超过 {cap_hint}。\n供方履约保障（守约偏向）：乙方未按期交付合格成果或货物的，每迟延一日应向甲方支付逾期违约金；迟延超过 15 日仍未纠正的，甲方有权单方书面通知解除合同，并要求乙方全额退还已收未履约款项及赔偿实际直接损失。\n维权成本承担：因违约方违约引发争议的，守约方因维权合理支出的律师费、保全保险费、公证费、差旅费及诉讼费用均由违约方据实承担。"""
    elif "乙方" in role_str:
        breach = f"""违约金约定：双方违约金严格遵循对等公平原则，违约金计算标准按逾期金额的 {rate_hint} 按日计收，累计总额不超过 {cap_hint}。\n付款履行保障（供方偏向）：甲方逾期付款的，每逾期一日应向乙方支付逾期利息；逾期付款超过 15 日的，乙方有权暂停后续交付或技术服务且不承担迟延违约责任，交付工期相应合理顺延。\n损失责任限额：除故意或重大过失外，乙方对甲方承担的违约赔偿责任总额以本合同实际收取的服务价款为上限，且乙方不承担任何间接损失或预期商业利润损失。"""
    else:
        breach = f"""双方权责对等：任何一方违反本合同义务，应依照《中华人民共和国民法典》承担违约责任，赔偿守约方的直接经济损失。\n违约金标准：违约方每逾期履行一日，应按逾期未履行部分金额的 {rate_hint} 向守约方支付违约金，违约金累计总额以 {cap_hint} 为限。\n维权合理支出：违约方应当承担守约方为维护自身合法权益所支付的合理律师费、诉讼仲裁费与调查取证费。"""

    return breach, jurisdiction


def render_contract_draft(
    contract_type: str,
    party_a: str,
    party_b: str,
    core_subject: str,
    payment_terms: str = "",
    special_terms: str = "",
    client_role: str = "甲方"
) -> str:
    """
    依据国家标准示范文本，毫秒级快速合成高标准正式合同初稿。
    """
    tmpl_data = match_template(contract_type)
    
    now = datetime.datetime.now()
    year_str = str(now.year)
    date_str = f"{now.year} 年 {now.month:02d} 月 {now.day:02d} 日"
    code_str = f"{now.strftime('%m%d%H%M')}"
    code_prefix = tmpl_data.get("code_prefix", "AGR")
    
    # 格式化核心标的
    if core_subject and core_subject.strip():
        core_subject_formatted = "   " + core_subject.strip()
    else:
        core_subject_formatted = "   双方按照业务订单明确的技术要求、产品规格型号、单价及交付数量据实执行。"

    # 格式化付款条款
    if payment_terms and payment_terms.strip():
        payment_terms_formatted = f"   (1) 具体结算节点：{payment_terms.strip()}\n   (2) 结算币种为人民币，通过法定企业银行对公转账结算。"
    else:
        payment_terms_formatted = "   双方实行分期结算：合同签署生效后付 30% 预付款，阶段交验合格付 60%，剩余 10% 质保金期满后结清。"

    # 格式化特约商业条款
    if special_terms and special_terms.strip():
        special_terms_clause = f"   本合同特别商定以下专属商业条款（优先于其他常规约定适用）：\n   \"{special_terms.strip()}\"\n   上述特约由双方慎重协商订立，具备同等最高法律约束力。"
    else:
        special_terms_clause = "   双方无其他未列明的除外特约商业事项。如有未尽事宜，双方协商签订书面补充协议。"

    # 违约与管辖
    breach_clauses, jurisdiction_clause = build_breach_and_jurisdiction(
        client_role=client_role,
        special_terms=special_terms,
        party_a=party_a or "甲方",
        party_b=party_b or "乙方"
    )

    # 拼装全文
    lines = []
    lines.append(f"{tmpl_data['title']}\n")
    lines.append(f"合同编号：CT-{year_str}-{code_prefix}-{code_str}")
    lines.append(f"签署日期：{date_str}")
    lines.append(f"签署地点：合同签订地（以实际盖章地为准）\n")
    lines.append(f"甲方（委托方 / 采购方）：{party_a.strip() if party_a else '某某采购方企业有限公司'}")
    lines.append(f"统一社会信用代码：91110108MA01XXXX7K")
    lines.append(f"法定代表人 / 授权代表：法定代表人")
    lines.append(f"住所地及通讯地址：北京市海淀区科技园区")
    lines.append(f"联系电话：010-8888XXXX\n")
    lines.append(f"乙方（服务方 / 供应方）：{party_b.strip() if party_b else '某某供应方技术有限公司'}")
    lines.append(f"统一社会信用代码：91310115MA1KXXXX8L")
    lines.append(f"法定代表人 / 授权代表：法定代表人")
    lines.append(f"住所地及通讯地址：上海市浦东新区高科技园区")
    lines.append(f"联系电话：021-6666XXXX\n")
    lines.append(f"{tmpl_data['intro']}\n")

    for article_title, paragraphs in tmpl_data["articles"]:
        lines.append(article_title)
        for p in paragraphs:
            rendered_p = p.format(
                core_subject_formatted=core_subject_formatted,
                payment_terms_formatted=payment_terms_formatted,
                breach_clauses=breach_clauses,
                special_terms_clause=special_terms_clause,
                jurisdiction_clause=jurisdiction_clause
            )
            lines.append(rendered_p)
        lines.append("")

    lines.append("（以下无正文，为本合同签署盖章页）\n")
    lines.append(f"甲方（盖章）：{party_a.strip() if party_a else '某某采购方企业有限公司'}")
    lines.append("法定代表人 / 授权代表（签字）：________________")
    lines.append(f"签署日期：{year_str} 年    月    日\n")
    lines.append(f"乙方（盖章）：{party_b.strip() if party_b else '某某供应方技术有限公司'}")
    lines.append("法定代表人 / 授权代表（签字）：________________")
    lines.append(f"签署日期：{year_str} 年    月    日")

    return "\n".join(lines).strip()
