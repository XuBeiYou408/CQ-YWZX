def search_by_risk_point(risk_point: str, top_k: int = 3) -> List[Dict[str, Any]]:
    """
    Agent 行动层入口：按「具体风险点」（而非整份合同）精准检索判例。
    与 search_precedents 共用评分内核，语义上强调调用方传入的是
    分诊/深查阶段识别出的具体风险描述（如「日5%违约金畸高」）。
    """
    return search_precedents(risk_point or "", top_k=top_k)


def get_precedent_by_case_no(case_no: str) -> Dict[str, Any] | None:
    """按案号（或其子串）精确取判例，供幻觉核验与引用追溯使用"""
    if not case_no:
        return None
    for p in PRECEDENTS_DATABASE:
        cn = p.get("case_no") or ""
        if case_no in cn or cn in case_no:
            return p
    return None


def search_precedents(contract_text: str, top_k: int = 3) -> List[Dict[str, Any]]:
    """
    根据合同正文与关键词，动态扫描并评分匹配最相关的最高法裁判指引与法条
    """
    import re
    text_lower = contract_text.lower()
    tokens = [w.strip().lower() for w in re.split(r'[\s,，、；;]+', contract_text) if len(w.strip()) >= 2]
    scored = []

    for prec in PRECEDENTS_DATABASE:
        score = 0
        prec_keywords = [k.lower() for k in prec["keywords"]]
        prec_cat = prec["category"].lower()
        prec_title = prec["title"].lower()

        # 1. 全文子串直接匹配
        for kw in prec_keywords:
            if kw in text_lower:
                count = text_lower.count(kw)
                score += (4 + min(count, 4) * 2)

        # 2. Token 分词双向交叉匹配
        for t in tokens:
            if t in prec_title or t in prec_cat:
                score += 5
            for kw in prec_keywords:
                if t in kw or kw in t:
                    score += 3

        if prec_cat in text_lower:
            score += 4

        if score > 0:
            scored.append((score, prec))

    scored.sort(key=lambda x: x[0], reverse=True)
    results = [item[1] for item in scored[:top_k]]

    # 兜底返回最核心的指引
    if len(results) < top_k:
        for fallback in PRECEDENTS_DATABASE:
            if fallback not in results:
                results.append(fallback)
            if len(results) >= top_k:
                break

    return results

