# ======================================================================
# 统一 Prompt 渲染器
# ----------------------------------------------------------------------
# 背景：各 Prompt 的 JSON 示例写作 {{...}}（本意为 .format() 转义），但部分
# 调用点使用 str.replace() 填充占位符，导致双花括号原样送入模型，模型会
# 模仿输出 `{{"clauses": [...]}}` 这类畸形 JSON，造成解析失败与规划回退。
# 本函数统一渲染：先做占位符替换，再把被转义的双花括号还原为单花括号。
# ======================================================================
def render_prompt(template: str, **kwargs) -> str:
    """渲染 Prompt 模板：占位符替换 + 转义花括号还原"""
    text = template
    for key, value in kwargs.items():
        text = text.replace("{" + key + "}", str(value))
    # 占位符替换完成后再还原 JSON 示例中的双花括号（避免误伤占位符）
    text = text.replace("{{", "{").replace("}}", "}")
    return text
