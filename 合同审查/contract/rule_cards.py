def scan_rules(text: str) -> List[Dict[str, Any]]:
    """
    条款级规则扫描：对任意文本（整份合同或单条条款）执行 5 组高危规则穿透。
    返回命中项（含渲染好的卡片 Markdown，{clause_quote} 占位符保留，
    由调用方决定引用原文：整报兜底用固定引述，交叉验证用真实条款文本）。
    """
    hits: List[Dict[str, Any]] = []
    if not text:
        return hits
    for rule in RULE_CARDS:
        matched_keywords = [k for k in rule["keywords"] if k in text]
        if matched_keywords:
            hits.append({
                "rule_id": rule["id"],
                "title": rule["title"],
                "severity": rule["severity"],
                "matched_keywords": matched_keywords,
                "card_template": rule["card"],
                "suggestion": rule["suggestion"],
            })
    return hits


def render_rule_card(hit: Dict[str, Any], clause_quote: str) -> str:
    """渲染规则卡片：clause_quote 为【条款原文引述】的实际内容"""
    return hit["card_template"].replace("{clause_quote}", clause_quote)


